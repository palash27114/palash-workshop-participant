#!/usr/bin/env bash
# Script: Run the talent-etl pipeline as a Kubernetes Job on the workshop EKS cluster
# Purpose: Ship ALL job modules (not only job.py) plus settings to EKS and run Bronze -> Silver -> Gold
#          against Aurora PostgreSQL and the S3 data lake. No changes to infra/ or bin/.
# Usage:   data/talent-etl/deploy/cloud_run.sh [job.py arguments, e.g. --layers silver,gold]
# Prereq:  data/talent-etl/deploy/cloud_setup.sh has been run (after the latest ./bin/deploy-backend.sh).

set -euo pipefail

JOB_DIR="$(cd "$(dirname "$0")/.." && pwd -P)"
PROJECT_ROOT="$(cd "$JOB_DIR/../.." && pwd -P)"
cd "$PROJECT_ROOT"
export PATH="$HOME/.local/bin:$PATH"

./bin/setup-participant.sh > /dev/null
source ENVIRONMENT.config
export AWS_REGION="${AWS_REGION:-ap-south-1}"

APP_ID="$PARTICIPANT_ID"
NAME="talent-etl-cloud"
BUCKET="coding-workshop-datalake-${APP_ID}"
RDS_CLUSTER="coding-workshop-rds-${APP_ID}"
IMAGE="jupyter/all-spark-notebook:latest"   # same image as the workshop's EKS jobs (Python 3.11)
JOB_ARGS="${*:-}"

echo "== Connecting kubectl to coding-workshop-${APP_ID}"
aws eks update-kubeconfig --region "$AWS_REGION" --name "coding-workshop-${APP_ID}" > /dev/null

echo "== Reading Aurora connection settings"
read -r PG_HOST PG_PORT PG_NAME PG_USER <<< "$(aws rds describe-db-clusters --db-cluster-identifier "$RDS_CLUSTER" \
    --query 'DBClusters[0].[Endpoint,Port,DatabaseName,MasterUsername]' --output text)"
# The master password is generated by Terraform; read it from the state without printing it.
PG_PASS="$(terraform -chdir=infra state pull | "$JOB_DIR/.venv/bin/python" -c '
import json, sys
state = json.load(sys.stdin)
for r in state["resources"]:
    if r["type"] == "aws_rds_cluster" and r["mode"] == "managed":
        print(r["instances"][0]["attributes"]["master_password"])
')"
[ -n "$PG_PASS" ] || { echo "ERROR: could not read the Aurora password from Terraform state"; exit 1; }
echo "  ${PG_USER}@${PG_HOST}:${PG_PORT}/${PG_NAME}"

echo "== Shipping code (all modules) and secrets to the cluster"
kubectl create configmap "${NAME}-code" --from-file="$JOB_DIR/requirements.txt" \
    $(for f in "$JOB_DIR"/*.py; do printf -- "--from-file=%s " "$f"; done) \
    --dry-run=client -o yaml | kubectl apply -f - > /dev/null
printf '%s' "$PG_PASS" | kubectl create secret generic "${NAME}-db" --from-file=POSTGRES_PASS=/dev/stdin \
    --dry-run=client -o yaml | kubectl apply -f - > /dev/null
unset PG_PASS

echo "== Starting job ${NAME}"
kubectl delete job "$NAME" --ignore-not-found --wait=true > /dev/null
kubectl apply -f - << EOF
apiVersion: batch/v1
kind: Job
metadata:
  name: ${NAME}
  labels: {app.kubernetes.io/name: talent-etl, app.kubernetes.io/part-of: coding-workshop}
spec:
  backoffLimit: 1
  ttlSecondsAfterFinished: 86400
  template:
    metadata:
      labels: {app.kubernetes.io/name: talent-etl}
    spec:
      restartPolicy: Never
      # The node allows one hop to its credential service (IMDSv2 hop limit 1); running on the node's
      # network lets the job use the node role (which has the data-lake policy) without extra infra.
      hostNetwork: true
      dnsPolicy: ClusterFirstWithHostNet
      containers:
        - name: talent-etl
          image: ${IMAGE}
          imagePullPolicy: IfNotPresent
          command: ["sh", "-c"]
          args:
            - |
              set -e
              pip install --no-cache-dir --quiet -r /app/requirements.txt
              cd /app && python job.py ${JOB_ARGS}
          env:
            - {name: PYTHONDONTWRITEBYTECODE, value: "1"}
            - {name: IS_LOCAL, value: "false"}
            - {name: APP_ID, value: "${APP_ID}"}
            - {name: AWS_REGION, value: "${AWS_REGION}"}
            - {name: AWS_DEFAULT_REGION, value: "${AWS_REGION}"}
            - {name: LAKE_BUCKET, value: "${BUCKET}"}
            - {name: POSTGRES_HOST, value: "${PG_HOST}"}
            - {name: POSTGRES_PORT, value: "${PG_PORT}"}
            - {name: POSTGRES_NAME, value: "${PG_NAME}"}
            - {name: POSTGRES_USER, value: "${PG_USER}"}
            - {name: SEED_SOURCE_DB, value: "true"}
          envFrom:
            - secretRef: {name: ${NAME}-db}
          volumeMounts:
            - {name: code, mountPath: /app}
          resources:
            requests: {cpu: 500m, memory: 1Gi}
            limits: {cpu: "1", memory: 2Gi}
      volumes:
        - name: code
          configMap: {name: ${NAME}-code}
EOF

echo "== Waiting for the job (image pull + pip install take a minute or two)"
for _ in $(seq 1 60); do
    STATUS="$(kubectl get job "$NAME" -o jsonpath='{.status.succeeded}/{.status.failed}')"
    [ "$STATUS" != "/" ] && break
    sleep 10
done
kubectl logs "job/${NAME}" --tail=200 | grep -vE "^\s*$" || true
echo ""
kubectl get job "$NAME"
if [ "$(kubectl get job "$NAME" -o jsonpath='{.status.succeeded}')" = "1" ]; then
    echo "SUCCESS: pipeline ran in AWS. Lake: s3://${BUCKET}/"
else
    echo "FAILED: see logs above (kubectl logs job/${NAME})"
    exit 1
fi
